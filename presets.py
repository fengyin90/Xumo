def load_user() -> list[tuple[str, str]]:
    """读用户自定义预设。文件缺失或损坏一律当空表 —— 它只是便利，不该阻断启动。"""
    try:
        with open(USER_FILE, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError):
        return []
    out: list[tuple[str, str]] = []
    for item in data if isinstance(data, list) else []:
        name = str(item.get("name", "")).strip()
        text = str(item.get("text", "")).strip()
        if name and text:
            out.append((name, text))
    return out


def _write_user(items: list[tuple[str, str]]) -> None:
    payload = [{"name": n, "text": t} for n, t in items]
    tmp = USER_FILE + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
    os.replace(tmp, USER_FILE)


def add_user(name: str, text: str) -> bool:
    """存一条自定义预设。同名则覆盖，返回是否有改动。"""
    name, text = name.strip(), text.strip()
    if not name or not text:
        return False
    items = load_user()
    for i, (n, _) in enumerate(items):
        if n == name:
            items[i] = (name, text)
            _write_user(items)
            return True
    items.append((name, text))
    _write_user(items)
    return True


def remove_user(name: str) -> bool:
    items = load_user()
    kept = [(n, t) for n, t in items if n != name]
    if len(kept) == len(items):
        return False
    _write_user(kept)
    return True


def all_presets() -> tuple[list[tuple[str, str]], list[tuple[str, str]]]:
    """返回 (内置, 自定义)。界面上要分开渲染 —— 自定义可删，内置不可删。"""
    return BUILTIN, load_user()
